"""Schnittstelle zur IT-Umgebung (Verzeichnis, Geräteverwaltung, Postfächer).

Der Agent ruft nie direkt PowerShell oder die Graph API auf, sondern nur diese Methoden mit festem Parameter-Schema.
Welche Umgebung dahintersteckt (Simulation, echte Umgebung), ist austauschbar.
"""
from __future__ import annotations

from typing import Protocol


class DirectoryError(Exception):
    """Fachlicher Fehler der Umgebung (Benutzer nicht gefunden, Gruppe existiert nicht, ...)."""


class Directory(Protocol):
    name: str

    # --- lesen ---
    def get_account_status(self, upn: str) -> dict: ...
    def get_group_memberships(self, upn: str) -> list[str]: ...
    def get_group_info(self, group: str) -> dict: ...
    def get_device_status(self, upn: str) -> list[dict]: ...
    def get_device_owner(self, device_id: str) -> str: ...
    def get_mailbox_info(self, upn: str) -> dict: ...
    def is_privileged(self, upn: str) -> bool: ...

    # --- schreiben ---
    def unlock_account(self, upn: str) -> dict: ...
    def lock_account(self, upn: str) -> dict: ...                  # nur für Rückgängig-Machen
    def disable_account(self, upn: str) -> dict: ...
    def enable_account(self, upn: str) -> dict: ...                # nur für Rückgängig-Machen
    def send_password_reset_link(self, upn: str) -> dict: ...
    def add_group_member(self, upn: str, group: str) -> dict: ...
    def remove_group_member(self, upn: str, group: str) -> dict: ...
    def trigger_device_sync(self, device_id: str) -> dict: ...
    def wipe_device(self, device_id: str) -> dict: ...
    def set_mailbox_forwarding(self, upn: str, address: str | None) -> dict: ...
